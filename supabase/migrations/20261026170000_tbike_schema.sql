-- T-BIKE MVP | PostgreSQL / Supabase | Sprint 3 migration (de xuat)
-- DANH DONG: 8 bang trong ERD v2. Thay doi duy nhat co chu dich:
-- tai_khoan_nhan_vien: KHONG luu mat_khau_bam; them auth_user_id lien ket auth.users(id).
-- Phai review thay doi nay truoc khi chot migration.
-- Tai lieu nao da tao bang tren remote thi KHONG chay lai file nay tren cung DB.

begin;

-- 1. Mien gia tri
create type public.loai_xe_enum as enum ('Manual', 'Automatic');
create type public.trang_thai_xe_enum as enum ('KhaDung', 'DangThue', 'CanBaoDuong');
create type public.trang_thai_yeu_cau_enum as enum ('DaGui', 'DaXacNhan', 'DangThue', 'HoanTat', 'TuChoi');
create type public.trang_thai_bao_dam_enum as enum ('ChuaKiemTra', 'DaXacNhan', 'DaHoanTra');
create type public.vai_tro_nhan_vien_enum as enum ('ChuCuaHang', 'NhanVien');

-- 2. D3 - Quy tac nghiep vu
create table public.bang_gia_thue (
  loai_xe public.loai_xe_enum primary key,
  don_gia_ngay_vnd bigint not null check (don_gia_ngay_vnd > 0)
);

create table public.quy_tac_phi_tre (
  ma_quy_tac varchar(8) primary key,
  tu_gio_tre numeric(8,4) not null check (tu_gio_tre >= 0),
  gom_moc_duoi boolean not null default true,
  den_gio_tre numeric(8,4),
  gom_moc_tren boolean not null default false,
  he_so_ngay numeric(3,2) not null check (he_so_ngay in (0.00, 0.50, 1.00)),
  constraint ck_khoang_gio_hop_le check (den_gio_tre is null or den_gio_tre >= tu_gio_tre)
);

create table public.quy_tac_bao_duong (
  ma_quy_tac varchar(8) primary key,
  nguong_km integer not null default 2000 check (nguong_km > 0)
);

create table public.phuong_thuc_bao_dam (
  ma_phuong_thuc varchar(30) primary key,
  ten_phuong_thuc varchar(100) not null unique,
  dang_ap_dung boolean not null default true
);

-- 3. NFR-03 - Ho so nhan vien. Supabase Auth quan ly mat khau.
create table public.tai_khoan_nhan_vien (
  ma_nhan_vien integer generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete restrict,
  ten_dang_nhap varchar(50) not null unique,
  ho_ten varchar(100) not null,
  vai_tro public.vai_tro_nhan_vien_enum not null default 'NhanVien',
  dang_hoat_dong boolean not null default true,
  ngay_tao timestamptz not null default now()
);

-- 4. D1 - Xe / ODO
create table public.xe (
  ma_xe varchar(10) primary key,
  ten_xe varchar(50) not null,
  loai_xe public.loai_xe_enum not null references public.bang_gia_thue(loai_xe) on delete restrict,
  trang_thai public.trang_thai_xe_enum not null default 'KhaDung',
  odo_hien_tai integer not null default 0,
  odo_bao_duong_gan_nhat integer not null default 0,
  ngay_bao_duong_gan_nhat date,
  ma_quy_tac_bao_duong varchar(8) not null default 'BRULE-04' references public.quy_tac_bao_duong(ma_quy_tac) on delete restrict,
  constraint ck_odo_xe check (odo_hien_tai between 0 and 999999),
  constraint ck_odo_bao_duong check (odo_bao_duong_gan_nhat between 0 and odo_hien_tai)
);
create index idx_xe_loai_trang_thai on public.xe (loai_xe, trang_thai);

create table public.lich_su_bao_duong (
  ma_lan_bao_duong bigint generated by default as identity primary key,
  ma_xe varchar(10) not null references public.xe(ma_xe) on delete restrict,
  ngay_bao_duong date not null,
  odo_luc_bao_duong integer not null,
  nguoi_ghi_nhan integer not null references public.tai_khoan_nhan_vien(ma_nhan_vien) on delete restrict,
  ghi_chu varchar(255),
  thoi_diem_ghi_nhan timestamptz not null default now(),
  constraint ck_odo_luc_bao_duong check (odo_luc_bao_duong between 0 and 999999)
);
create index idx_lich_su_bao_duong_xe on public.lich_su_bao_duong (ma_xe, ngay_bao_duong);

-- 5. D2 - Yeu cau / Don thue mot vong doi
create table public.yeu_cau_thue (
  ma_yeu_cau varchar(12) primary key,
  ma_don_thue varchar(12) unique,
  ma_xe varchar(10) not null references public.xe(ma_xe) on delete restrict,
  ho_ten_khach varchar(100) not null,
  so_dien_thoai varchar(11) not null,
  ghi_chu_yeu_cau varchar(255),
  thoi_gian_nhan_du_kien timestamptz not null,
  thoi_gian_tra_du_kien timestamptz not null,
  thoi_diem_giao_xe timestamptz,
  thoi_gian_tra_thuc_te timestamptz,
  odo_giao_xe integer,
  odo_nhan_xe integer,
  quang_duong_luot_thue integer,
  don_gia_ap_dung_vnd bigint,
  ma_phuong_thuc_bao_dam varchar(30) references public.phuong_thuc_bao_dam(ma_phuong_thuc) on delete restrict,
  trang_thai_bao_dam public.trang_thai_bao_dam_enum not null default 'ChuaKiemTra',
  so_gio_tre numeric(12,4) not null default 0,
  ma_quy_tac_phi_tre varchar(8) references public.quy_tac_phi_tre(ma_quy_tac) on delete restrict,
  he_so_phi_tre_ap_dung numeric(3,2) not null default 0,
  phu_phi_tre_han_vnd bigint not null default 0,
  trang_thai_xu_ly public.trang_thai_yeu_cau_enum not null default 'DaGui',
  nguoi_xac_nhan integer references public.tai_khoan_nhan_vien(ma_nhan_vien) on delete restrict,
  ngay_tao timestamptz not null default now(),
  ngay_cap_nhat timestamptz not null default now(),

  constraint ck_thoi_gian_du_kien check (thoi_gian_tra_du_kien > thoi_gian_nhan_du_kien),
  constraint ck_odo_giao check (odo_giao_xe is null or odo_giao_xe >= 0),
  constraint ck_odo_nhan check (odo_nhan_xe is null or odo_nhan_xe >= 0),
  constraint ck_thu_tu_odo check (odo_nhan_xe is null or odo_giao_xe is null or odo_nhan_xe >= odo_giao_xe),
  constraint ck_quang_duong check (quang_duong_luot_thue is null or (odo_giao_xe is not null and odo_nhan_xe is not null and quang_duong_luot_thue = odo_nhan_xe - odo_giao_xe)),
  constraint ck_thoi_gian_thuc_te check (thoi_diem_giao_xe is null or thoi_gian_tra_thuc_te is null or thoi_gian_tra_thuc_te >= thoi_diem_giao_xe),
  constraint ck_don_gia_ap_dung check (don_gia_ap_dung_vnd is null or don_gia_ap_dung_vnd > 0),
  constraint ck_phi_tre_hop_le check (so_gio_tre >= 0 and phu_phi_tre_han_vnd >= 0 and he_so_phi_tre_ap_dung in (0.00, 0.50, 1.00)),
  constraint ck_don_da_xac_nhan check (trang_thai_xu_ly not in ('DaXacNhan','DangThue','HoanTat') or (ma_don_thue is not null and don_gia_ap_dung_vnd is not null)),
  constraint ck_du_lieu_dong_don check (trang_thai_xu_ly <> 'HoanTat' or (thoi_gian_tra_thuc_te is not null and odo_giao_xe is not null and odo_nhan_xe is not null))
);
create index idx_lich_thue_theo_xe on public.yeu_cau_thue (ma_xe, thoi_gian_nhan_du_kien, thoi_gian_tra_du_kien);
create index idx_trang_thai_yeu_cau on public.yeu_cau_thue (trang_thai_xu_ly);
create index idx_so_dien_thoai on public.yeu_cau_thue (so_dien_thoai);

-- Chi so updated_at khong tu cap nhat: backend/tiep theo co the them trigger.
-- DO NOT expose public tables to clients until proper grants + RLS policies are reviewed.

alter table public.bang_gia_thue enable row level security;
alter table public.quy_tac_phi_tre enable row level security;
alter table public.quy_tac_bao_duong enable row level security;
alter table public.phuong_thuc_bao_dam enable row level security;
alter table public.tai_khoan_nhan_vien enable row level security;
alter table public.xe enable row level security;
alter table public.lich_su_bao_duong enable row level security;
alter table public.yeu_cau_thue enable row level security;

-- Mo hinh khoi dau: chi backend tin cay duoc phep truy cap bang.
-- Khach hang xem xe / gui yeu cau qua API backend, KHONG truc tiep ket noi bang bang publishable key.
revoke all on table
  public.bang_gia_thue,
  public.quy_tac_phi_tre,
  public.quy_tac_bao_duong,
  public.phuong_thuc_bao_dam,
  public.tai_khoan_nhan_vien,
  public.xe,
  public.lich_su_bao_duong,
  public.yeu_cau_thue
from anon, authenticated;

commit;
